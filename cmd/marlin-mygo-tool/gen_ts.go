// runGenTS reads the canonical compiled Protobuf FileDescriptorSet
// (proto/marlin-wire-v1.bin) and generates zero-drift TypeScript interfaces
// and enum union types for @tao3k/marlin-panel-sdk using Pure Go.
func runGenTS(args []string) error {
	fs := flag.NewFlagSet("gen-ts", flag.ContinueOnError)
	descPath := fs.String("descriptor", "proto/marlin-wire-v1.bin", "path to compiled FileDescriptorSet")
	outPath := fs.String("out", "packages/panel-sdk/src/generated/wire_types.ts", "output TypeScript definitions file")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if _, err := os.Stat(*descPath); err != nil {
		if err := runDescriptor([]string{"-out", *descPath}); err != nil {
			return err
		}
	}
	raw, err := os.ReadFile(*descPath)
	if err != nil {
		return err
	}
	var fds descriptorpb.FileDescriptorSet
	if err := proto.Unmarshal(raw, &fds); err != nil {
		return fmt.Errorf("unmarshal descriptor set: %w", err)
	}
	tsCode := generateTSFromDescriptorSet(&fds)
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(*outPath, []byte(tsCode), 0o644); err != nil {
		return err
	}
	fmt.Printf("Generated TypeScript wire types from %s -> %s (%d bytes)\n", *descPath, *outPath, len(tsCode))
	return nil
}

func generateTSFromDescriptorSet(fds *descriptorpb.FileDescriptorSet) string {
	var files []*descriptorpb.FileDescriptorProto
	mapEntries := make(map[string]*descriptorpb.DescriptorProto)
	for _, f := range fds.File {
		if strings.HasPrefix(f.GetPackage(), "marlin.") {
			files = append(files, f)
			collectMapEntries("."+f.GetPackage(), f.MessageType, mapEntries)
		}
	}
	slices.SortFunc(files, func(a, b *descriptorpb.FileDescriptorProto) int {
		return strings.Compare(a.GetName(), b.GetName())
	})

	var buf bytes.Buffer
	// REUSE-IgnoreStart
	buf.WriteString("// SPDX-FileCopyrightText: 2026 tao3k team and Contributors\n")
	buf.WriteString("//\n")
	buf.WriteString("// SPDX-License-Identifier: Apache-2.0 AND LGPL-2.1-or-later\n\n")
	// REUSE-IgnoreEnd
	buf.WriteString("// Code generated by marlin-mygo-tool gen-ts from proto/marlin-wire-v1.bin. DO NOT EDIT.\n\n")
	buf.WriteString("/** 64-bit wire integers encoded as decimal strings to avoid IEEE-754 2^53 precision loss. */\n")
	buf.WriteString("export type WireUint64 = string;\n")
	buf.WriteString("export type WireInt64 = string;\n")
	buf.WriteString("export type WireBytes = string;\n\n")

	for _, f := range files {
		fmt.Fprintf(&buf, "// --- %s (%s) ---\n\n", f.GetName(), f.GetPackage())
		prefix := pkgPrefix(f.GetPackage())
		for _, e := range f.EnumType {
			emitTSEnum(&buf, prefix, e)
		}
		for _, m := range f.MessageType {
			emitTSMessage(&buf, prefix, m, mapEntries)
		}
	}
	return buf.String()
}

func collectMapEntries(scope string, msgs []*descriptorpb.DescriptorProto, out map[string]*descriptorpb.DescriptorProto) {
	for _, m := range msgs {
		fqn := scope + "." + m.GetName()
		if m.GetOptions().GetMapEntry() {
			out[fqn] = m
		}
		collectMapEntries(fqn, m.NestedType, out)
	}
}

func pkgPrefix(pkg string) string {
	// e.g. "marlin.plugin.v1" -> "PluginV1"
	parts := strings.Split(pkg, ".")
	if len(parts) >= 3 && parts[0] == "marlin" {
		parts = parts[1:]
	}
	var b strings.Builder
	for _, p := range parts {
		if len(p) == 0 {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func emitTSEnum(buf *bytes.Buffer, prefix string, e *descriptorpb.EnumDescriptorProto) {
	name := prefix + e.GetName()
	vals := make([]string, 0, len(e.Value))
	for _, v := range e.Value {
		vals = append(vals, fmt.Sprintf("%q", v.GetName()))
	}
	fmt.Fprintf(buf, "export type %s = %s;\n\n", name, strings.Join(vals, " | "))
}

func emitTSMessage(buf *bytes.Buffer, prefix string, m *descriptorpb.DescriptorProto, mapEntries map[string]*descriptorpb.DescriptorProto) {
	if m.GetOptions().GetMapEntry() {
		return
	}
	name := prefix + m.GetName()
	for _, nestedEnum := range m.EnumType {
		emitTSEnum(buf, name, nestedEnum)
	}
	for _, nested := range m.NestedType {
		emitTSMessage(buf, name, nested, mapEntries)
	}
	fmt.Fprintf(buf, "export interface %s {\n", name)
	for _, fld := range m.Field {
		jsonName := fld.GetJsonName()
		if jsonName == "" {
			jsonName = fld.GetName()
		}
		tsType := tsFieldType(fld, mapEntries)
		fmt.Fprintf(buf, "  readonly %s?: %s;\n", jsonName, tsType)
	}
	buf.WriteString("}\n\n")
}

func tsFieldType(fld *descriptorpb.FieldDescriptorProto, mapEntries map[string]*descriptorpb.DescriptorProto) string {
	if fld.GetType() == descriptorpb.FieldDescriptorProto_TYPE_MESSAGE {
		if entry, isMap := mapEntries[fld.GetTypeName()]; isMap && len(entry.Field) == 2 {
			valType := tsScalarOrRefType(entry.Field[1])
			return fmt.Sprintf("Record<string, %s>", valType)
		}
	}
	base := tsScalarOrRefType(fld)
	if fld.GetLabel() == descriptorpb.FieldDescriptorProto_LABEL_REPEATED {
		return fmt.Sprintf("readonly (%s)[]", base)
	}
	return base
}

func tsScalarOrRefType(fld *descriptorpb.FieldDescriptorProto) string {
	switch fld.GetType() {
	case descriptorpb.FieldDescriptorProto_TYPE_BOOL:
		return "boolean"
	case descriptorpb.FieldDescriptorProto_TYPE_STRING:
		return "string"
	case descriptorpb.FieldDescriptorProto_TYPE_BYTES:
		return "WireBytes"
	case descriptorpb.FieldDescriptorProto_TYPE_INT64,
		descriptorpb.FieldDescriptorProto_TYPE_SINT64,
		descriptorpb.FieldDescriptorProto_TYPE_SFIXED64:
		return "WireInt64"
	case descriptorpb.FieldDescriptorProto_TYPE_UINT64,
		descriptorpb.FieldDescriptorProto_TYPE_FIXED64:
		return "WireUint64"
	case descriptorpb.FieldDescriptorProto_TYPE_DOUBLE,
		descriptorpb.FieldDescriptorProto_TYPE_FLOAT,
		descriptorpb.FieldDescriptorProto_TYPE_INT32,
		descriptorpb.FieldDescriptorProto_TYPE_UINT32,
		descriptorpb.FieldDescriptorProto_TYPE_SINT32,
		descriptorpb.FieldDescriptorProto_TYPE_FIXED32,
		descriptorpb.FieldDescriptorProto_TYPE_SFIXED32:
		return "number"
	case descriptorpb.FieldDescriptorProto_TYPE_MESSAGE, descriptorpb.FieldDescriptorProto_TYPE_ENUM:
		return resolveFQTypeName(fld.GetTypeName())
	default:
		return "unknown"
	}
}

func resolveFQTypeName(fqn string) string {
	trimmed := strings.TrimPrefix(fqn, ".")
	if strings.HasPrefix(trimmed, "google.protobuf.") {
		switch trimmed {
		case "google.protobuf.Timestamp":
			return "string"
		case "google.protobuf.Struct":
			return "Record<string, unknown>"
		default:
			return "unknown"
		}
	}
	// e.g. "marlin.plugin.v1.ScopedPanelEvent" -> "PluginV1ScopedPanelEvent"
	parts := strings.Split(trimmed, ".")
	if len(parts) >= 4 && parts[0] == "marlin" {
		prefix := pkgPrefix(strings.Join(parts[:3], "."))
		return prefix + strings.Join(parts[3:], "")
	}
	return "unknown"
}
