package main

import (
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const wireLockFile = "proto/wire-lock.toml"

// runWireSync computes deterministic SHA-256 digests across proto/marlin-wire-v1.bin
// and all canonical .proto contracts, optionally verifying parity against a local
// marlin-agent-core checkout and checking/updating proto/wire-lock.toml.
func runWireSync(args []string) error {
	fs := flag.NewFlagSet("wire-sync", flag.ContinueOnError)
	coreDir := fs.String("core", "", "optional path to marlin-agent-core checkout for cross-repo drift verification")
	checkOnly := fs.Bool("check", false, "fail if proto/wire-lock.toml drifts from current descriptor/protos")
	if err := fs.Parse(args); err != nil {
		return err
	}

	descBytes, err := os.ReadFile("proto/marlin-wire-v1.bin")
	if err != nil {
		return fmt.Errorf("read proto/marlin-wire-v1.bin: %w", err)
	}
	descSum := sha256Hex(descBytes)

	var b strings.Builder
	// REUSE-IgnoreStart
	b.WriteString("# SPDX-FileCopyrightText: 2026 tao3k team and Contributors\n")
	b.WriteString("#\n")
	b.WriteString("# SPDX-License-Identifier: Apache-2.0 AND LGPL-2.1-or-later\n\n")
	// REUSE-IgnoreEnd
	b.WriteString("# Deterministic Protobuf wire-contract lockfile (generated by `marlin-mygo-tool wire-sync`).\n")
	b.WriteString("schema_version = 1\n")
	fmt.Fprintf(&b, "descriptor_path = %q\n", "proto/marlin-wire-v1.bin")
	fmt.Fprintf(&b, "descriptor_sha256 = %q\n", descSum)
	fmt.Fprintf(&b, "descriptor_bytes = %d\n\n", len(descBytes))
	b.WriteString("[protos]\n")
	for _, p := range canonicalProtos {
		raw, err := os.ReadFile(p)
		if err != nil {
			return fmt.Errorf("read %s: %w", p, err)
		}
		fmt.Fprintf(&b, "%q = %q\n", p, sha256Hex(raw))
	}

	if strings.TrimSpace(*coreDir) != "" {
		upstreamAppProto := filepath.Join(*coreDir, "crates", "marlin-agent-app-server", "proto", "marlin", "app", "v1", "app_server.proto")
		if _, statErr := os.Stat(upstreamAppProto); statErr != nil {
			return fmt.Errorf("upstream marlin-agent-core app_server.proto not found at %s: %w", upstreamAppProto, statErr)
		}
		if err := runCompatCheck([]string{"-core", *coreDir}); err != nil {
			return fmt.Errorf("cross-repo compat-check failed: %w", err)
		}
	}

	expected := b.String()
	if *checkOnly {
		existing, err := os.ReadFile(wireLockFile)
		if err != nil {
			return fmt.Errorf("read %s: %w (run `marlin-mygo-tool wire-sync` to generate)", wireLockFile, err)
		}
		if string(existing) != expected {
			return fmt.Errorf("%s is out of date with proto/marlin-wire-v1.bin; run `just proto-sync`", wireLockFile)
		}
		fmt.Printf("Wire lockfile verified: %s (descriptor sha256=%s, %d protos)\n", wireLockFile, descSum[:16], len(canonicalProtos))
		return nil
	}

	if err := os.WriteFile(wireLockFile, []byte(expected), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", wireLockFile, err)
	}
	fmt.Printf("Updated %s (descriptor sha256=%s, %d protos)\n", wireLockFile, descSum[:16], len(canonicalProtos))
	return nil
}

func sha256Hex(raw []byte) string {
	sum := sha256.Sum256(raw)
	return hex.EncodeToString(sum[:])
}
